library(readr);library(dplyr);library(ggplot2)
set.seed(1)
base="C:/Users/18904/Github/huashu-cup";od=file.path(base,"解答","1-第一题")
d=read_csv(file.path(base,"题目","附件数据","workload_trace_Sheet1.csv"),locale=locale(encoding="UTF-8"),show_col_types=FALSE)
d=d%>%mutate(gpu_h=`图形处理器需求量`*`连续执行时长`/60,`任务类型`=factor(`任务类型`,levels=c("实时推理任务","批量推理任务","人工智能训练任务")),`来源区域`=factor(`来源区域`,levels=c("区域A","区域B","区域C","区域D","区域E","区域F")))
cols=c("实时推理任务"="#E64B35","批量推理任务"="#4DBBD5","人工智能训练任务"="#00A087")
g1=ggplot(d,aes(x=`任务类型`,y=`图形处理器需求量`,fill=`任务类型`))+geom_boxplot(outlier.size=.5,outlier.alpha=.35,alpha=.9)+scale_fill_manual(values=cols)+labs(x=NULL,y="图形处理器需求量（等效GPU）")+theme_bw()+theme(legend.position="none")
ggsave(file.path(od,"需求分布_箱线图.png"),g1,width=9,height=6,dpi=150)
agg=d%>%group_by(`来源区域`,`任务类型`)%>%summarise(gpu_h=sum(gpu_h),.groups="drop")
g2=ggplot(agg,aes(x=`来源区域`,y=gpu_h,fill=`任务类型`))+geom_col(position="stack",width=.7)+scale_fill_manual(values=cols)+labs(x="区域",y="图形处理器-小时总量",fill="任务类型")+theme_bw()+theme(legend.position="bottom")
ggsave(file.path(od,"需求分布_堆叠柱状图.png"),g2,width=9,height=6,dpi=150)
